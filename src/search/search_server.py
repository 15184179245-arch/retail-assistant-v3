def _llm_rewrite_call(model: str, prompt: str) -> dict | None:
    try:
        import urllib.request as _ur
        body = _json.dumps({"model": model, "messages": [{"role": "user", "content": prompt}], "temperature": 0.1, "max_tokens": 1024}).encode()
        _lu = urlparse(LLM_API_URL)
        req = _ur.Request(LLM_API_URL, data=body, headers={"Content-Type": "application/json", "Authorization": f"Bearer {LLM_API_KEY}"})
        if _lu.scheme != "https" or not _lu.hostname or "." not in _lu.hostname \
                or _lu.hostname in ("127.0.0.1", "localhost"):
            return None  # F6: LLM egress https public domains only; else silent degrade
        resp = _ur.urlopen(req, timeout=LLM_TIMEOUT)
        text = _json.loads(resp.read())["choices"][0]["message"]["content"]
        m = re.search(r'\{.*"rewrite".*"verdict".*\}', text, re.DOTALL)
        if m:
            data = _json.loads(m.group())
            return {"rewrite": data.get("rewrite", []), "verdict": str(data.get("verdict", "unknown"))}
    except Exception:
        pass
    return None

def _parse_rewrite_text(text: str) -> dict | None:
    """F5: 与 _llm_rewrite_call 同款 JSON 抽取，作用于本地通道返回的纯文本。"""
    if not text:
        return None
    m = re.search(r'\{.*"rewrite".*"verdict".*\}', text, re.DOTALL)
    if not m:
        return None
    try:
        data = _json.loads(m.group())
        return {"rewrite": data.get("rewrite", []), "verdict": str(data.get("verdict", "unknown"))}
    except Exception:
        return None

def _llm_rewrite(keyword: str) -> dict:
    if not keyword or not keyword.strip():
        return {"rewrite": [keyword], "verdict": "unknown"}
    _loc = local_llm_config()  # F5: 本地小模型通道（高频轻任务优先，断网可用；回环白名单见 utils/localllm）
    if not LLM_API_KEY and _loc is None:
        return {"rewrite": [keyword], "verdict": "unknown"}
    with _LLM_REWRITE_LOCK:
        if keyword in _LLM_REWRITE_CACHE:
            return _LLM_REWRITE_CACHE[keyword]
    if keyword in _LLM_REWRITE_INFLIGHT:
        return {"rewrite": [keyword], "verdict": "unknown"}
    _LLM_REWRITE_INFLIGHT.add(keyword)
    try:
        result = None
        if _loc is not None:
            result = _parse_rewrite_text(_local_chat(
                _loc[0], _loc[1],
                [{"role": "user", "content": _REWRITE_PROMPT.format(keyword)}],
                temperature=0.1, max_tokens=128, timeout=20))
        if result is None:
            result = _llm_rewrite_call(LLM_MODEL, _REWRITE_PROMPT.format(keyword))
        if result is None:
            result = _llm_rewrite_call(LLM_FALLBACK_MODEL, _REWRITE_FALLBACK_PROMPT.format(keyword))
        if result and result.get("rewrite"):
            if isinstance(result["rewrite"], str):
                result["rewrite"] = [result["rewrite"]]
            elif not isinstance(result["rewrite"], list):
                result["rewrite"] = [str(result["rewrite"])]
            with _LLM_REWRITE_LOCK:
                if len(_LLM_REWRITE_CACHE) < _LLM_REWRITE_CACHE_MAX:
                    _LLM_REWRITE_CACHE[keyword] = result
            return result
    except Exception:
        pass
    finally:
        _LLM_REWRITE_INFLIGHT.discard(keyword)
    _mark_llm_degraded()
    return {"rewrite": [keyword], "verdict": "unknown"}


def _b_path_task(keyword: str) -> tuple[dict | None, bool]:
    """S4 B 路：线程池里执行 LLM 改写，返回 (结果, 是否降级)。

    _llm_rewrite 内部的降级标记写在执行线程的 threading.local 上，不会自动出现在
    请求线程——因此这里同线程读回、随返回值显式带出。异常一律吞掉转为降级，
    绝不让 B 路失败演变成 5xx。
    """
    try:
        res = _llm_rewrite(keyword)
        return res, bool(getattr(_local, "_llm_degraded", False))
    except Exception:
        return None, True

