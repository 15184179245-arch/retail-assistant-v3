def _correct_search_query(keyword: str) -> tuple[str, str | None]:
    """Correct typos, homophones, and pinyin in search query. Returns (corrected, hint)."""
    kw = keyword.strip()
    if not kw:
        return kw, None

    # Layer 1: Full typo match
    if kw in TYPO_CORRECTIONS:
        corrected = TYPO_CORRECTIONS[kw]
        return corrected, f'您是不是要找"{corrected}"？'

    # Layer 2: Substring typo replacement
    corrected = kw
    changed = False
    for wrong, right in sorted(TYPO_CORRECTIONS.items(), key=lambda x: -len(x[0])):
        if wrong in corrected:
            corrected = corrected.replace(wrong, right)
            changed = True
    if changed:
        return corrected, f'已为您纠正为"{corrected}"'

    # Layer 3: Homophone replacement
    for (char, context), (replacement, full) in HOMOPHONE_CORRECTIONS.items():
        if context in kw and char in kw:
            pattern = context + char
            if pattern in kw:
                corrected = kw.replace(pattern, context + replacement)
                return corrected, f'已为您替换同音字，搜索"{corrected}"'

    # Layer 4: Pinyin match
    kw_lower = kw.lower().strip()
    if kw_lower in PINYIN_CORRECTIONS:
        corrected = PINYIN_CORRECTIONS[kw_lower]
        return corrected, f'拼音识别为"{corrected}"'

    # Layer 5: Fuzzy pinyin match (edit distance <= 2)
    if kw_lower.isascii() and kw_lower.isalpha() and len(kw_lower) >= 3:
        best_match = None
        best_dist = 999
        for py, zh in PINYIN_CORRECTIONS.items():
            dist = _levenshtein(kw_lower, py)
            if dist < best_dist and dist <= 2:
                best_dist = dist
                best_match = zh
        if best_match:
            return best_match, f'拼音识别为"{best_match}"'

    return kw, None


def _levenshtein(a: str, b: str) -> int:
    """Levenshtein edit distance."""
    m, n = len(a), len(b)
    if m > n:
        return _levenshtein(b, a)
    prev = list(range(m + 1))
    for j in range(1, n + 1):
        curr = [j] + [0] * m
        for i in range(1, m + 1):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            curr[i] = min(prev[i] + 1, curr[i - 1] + 1, prev[i - 1] + cost)
        prev = curr
    return prev[m]


def _build_synonym_index():
    """Pre-compute reverse synonym index at startup for O(1) lookup."""
    # key -> list of expanded terms (direct + substring matches)
    _direct = {}  # exact key match
    _reverse = {}  # value -> key (for reverse lookup)
    for k, v in SYNONYM_EXPANSIONS.items():
        for val in v.split("|"):
            val = val.strip()
            if val:
                _direct.setdefault(k, []).append(val)
                _reverse.setdefault(val, []).append(k)
    # Build substring match index: for each key, find all keys that contain it or are contained
    _substring = {}
    all_keys = list(SYNONYM_EXPANSIONS.keys())
    for k in all_keys:
        matches = []
        for other in all_keys:
            if k != other and (k in other or other in k):
                matches.append(other)
                matches.append(SYNONYM_EXPANSIONS[other])
        if matches:
            _substring[k] = list(dict.fromkeys(matches))
    return _direct, _reverse, _substring

_SYNONYM_DIRECT, _SYNONYM_REVERSE, _SYNONYM_SUBSTRING = _build_synonym_index()

