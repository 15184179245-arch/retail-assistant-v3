def _load_hardware_spec_tokens(db):
    """扫描商品 spec 与 name，用正则抽取复合五金规格型号注入 jieba，防止分词器切碎。"""
    spec_pattern = re.compile(r'[A-Za-z0-9]+(?:[\.][A-Za-z0-9]+)+')
    model_pattern = re.compile(r'\b[A-Za-z]+[0-9]+[A-Za-z0-9_]*\b')
    count = 0
    try:
        rows = db.execute("SELECT spec, name FROM products WHERE spec IS NOT NULL OR name IS NOT NULL").fetchall()
        for r in rows:
            for text in (r["spec"], r["name"]):
                if not text:
                    continue
                for m in spec_pattern.findall(text):
                    if len(m) >= 3 and not m.isdigit():
                        jieba.add_word(m, freq=2000, tag="spec")
                        count += 1
                for m in model_pattern.findall(text):
                    if len(m) >= 3:
                        jieba.add_word(m, freq=2000, tag="spec")
                        count += 1
        logging.info(f"五金规格型号词条注入: {count} 个词素")
    except Exception as e:
        logging.warning(f"规格词条加载异常: {e}")


