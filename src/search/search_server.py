            undotted_kw = clean_kw.replace(".", "")
            # S16c 扫码误读容错：数字码带前导零（个别枪对 EAN/ITF 补零读）时剥零再精确比，
            # 首扫「前导零变体」直达商品，不再落模糊层喷无关结果。
