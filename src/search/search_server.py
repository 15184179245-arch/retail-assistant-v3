def _fill_spec_from_name(db):
    rows = db.execute("SELECT id, name FROM products WHERE spec IS NULL OR spec = ''").fetchall()
    if not rows:
        return
    patterns = [
        (r'DN\d+(\.\d+)?', None),
        (r'\d+分', None),
        (r'\d+mm', None),
        (r'\d+[×x*]\d+([×x*]\d+)*', None),
        (r'\d+位', None),
        (r'\d+P', None),
        (r'\d+\.?\d*A', None),
        (r'\d+-\d+位', None),
        (r'\d+-\d+', None),
    ]
    filled = 0
    for row in rows:
        specs = []
        for pat, _ in patterns:
            m = re.search(pat, row["name"])
            if m and m.group() not in specs:
                specs.append(m.group())
        if specs:
            spec_val = "; ".join(specs)[:100]
            db.execute("UPDATE products SET spec=?, updated_at=datetime('now','localtime') WHERE id=?", (spec_val, row["id"]))
            filled += 1
            if filled % 500 == 0:
                db.commit()
    db.commit()
    logging.info(f"spec自动填充: {filled}/{len(rows)} 条")


