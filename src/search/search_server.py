def alias_unbind(data: dict) -> dict:
    """I24: 条码解绑（**回滚专用**，删 barcode_alias 行 + alias_audit(action=unbind)）。

    为什么需要它：条码改为「本地先生效 → 上游后台回写」后，后台校验没过
    （码已被别的商品占用 / 回读对不上 / 上游没这个商品）时必须把本地绑定**撤回**，
    否则本地会长期留一条管家婆不认的码——店员在 APP 扫得到、在收银端扫不到，
    正是对账不一致的源头（老板 2026-09-14 拍板：自动回滚 + 提示重来）。

    ``expect_sku`` 是**乐观锁**：只有该条码当前仍绑在它身上才删。回写是异步的，
    等待期间店员完全可能已经改判给别的商品——那种情况下回滚必须让路，
    否则会抹掉店员更新的操作（留痕事件照样记，reason=changed）。
    """
    barcode = (data.get("barcode") or "").strip()
    actor = (data.get("actor") or "").strip() or "unknown"
    expect_sku = (data.get("expect_sku") or "").strip()
    if not barcode:
        return _err("barcode 必填", "VALIDATION", "请提供条码")
    try:
        db = get_db()
        row = db.execute(
            "SELECT sku FROM barcode_alias WHERE barcode=? COLLATE NOCASE", (barcode,)
        ).fetchone()
        if not row:
            return _ok({"unbound": False, "barcode": barcode, "reason": "not_bound"})
        current = (row[0] or "").strip()
        if expect_sku and current != expect_sku:
            return _ok({"unbound": False, "barcode": barcode, "reason": "changed",
                        "current_sku": current})
        db.execute("DELETE FROM barcode_alias WHERE barcode=? COLLATE NOCASE", (barcode,))
        db.execute(
            "INSERT INTO alias_audit (barcode, sku, action, actor, created_at) "
            "VALUES (?,?,?,?,datetime('now','localtime'))",
            (barcode, current, "unbind", actor),
        )
        db.commit()
        _search_cache.clear()  # 解绑后旧检索结果立刻失效（同码不再命中该商品）
        return _ok({"unbound": True, "barcode": barcode, "sku": current})
    except Exception as e:
        return _err_db(f"解绑失败: {e}")


