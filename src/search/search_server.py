def _parse_batch_line(line: str) -> dict | None:
    """Parse a single batch pricing line into {name, qty}."""
    line = line.strip().replace(",", "，").replace(";", "；")
    if not line:
        return None
    # Priority 1: colon separator — 品名：数量
    m = re.match(r'^(.+?)[：:]\s*(\d+\.?\d*)\s*(?:' + _QTY_UNITS + r')?\s*$', line)
    if m:
        return {"name": m.group(1).strip(), "qty": float(m.group(2))}
    # Priority 2: qty-first — 5个 86盒 / 3根 4分管
    m = re.match(r'^(\d+\.?\d*)\s*(?:' + _QTY_FIRST_UNITS + r')\s+(.+)$', line)
    if m:
        return {"name": m.group(2).strip(), "qty": float(m.group(1))}
    # Priority 3: qty at end — 品名 10个 / 角阀×10 / 生料带 5
    m = re.match(r'^(.+?)\s*[×Xx*]?\s*(\d+\.?\d*)\s*(?:' + _QTY_UNITS + r')?\s*$', line)
    if m:
        return {"name": m.group(1).strip(), "qty": float(m.group(2))}
    return {"name": line, "qty": 1}


def _pad(s: str, width: int) -> str:
    """Pad string to visual width (CJK chars count as 2)."""
    vw = sum(2 if ord(c) > 127 else 1 for c in s)
    return s + " " * max(1, width - vw)


def _trunc(s: str, max_vw: int) -> str:
    """Truncate string to fit within max visual width."""
    vw = 0
    for i, c in enumerate(s):
        vw += 2 if ord(c) > 127 else 1
        if vw > max_vw:
            return s[:i]
    return s


def _format_batch_reply(results: list, original_items: list[dict]) -> str:
    """Format batch_price results into a table."""
    lines = []
    cols = ["编号", "名称", "规格", "售价", "进价", "库存", "数量"]
    cw = [12, 20, 12, 7, 7, 6, 7]
    sep = " "
    header = sep.join(_pad(cols[i], cw[i]) for i in range(len(cols)))
    lines.append(header)
    lines.append("-" * len(header))
    for i, r in enumerate(results):
        orig = original_items[i] if i < len(original_items) else None
        orig_name = orig.get("name", "") if orig else r.get("name", "")
        qty = r.get("qty", 1)
        qty_label = f"{int(qty)}个" if qty == int(qty) else f"{qty}个"
        if r.get("found"):
            code = r.get("sku", r.get("barcode", ""))
            row = [
                _trunc(code, cw[0]),
                _trunc(r.get("name", ""), cw[1]),
                _trunc(r.get("spec", "") or "-", cw[2]),
                f"{r.get('unit_price', 0):.2f}",
                f"{r.get('cost_price', 0):.2f}",
                str(r.get("stock_qty", 0)),
                qty_label,
            ]
            lines.append(sep.join(_pad(row[i], cw[i]) for i in range(len(cols))))
        else:
            lines.append(f"{_pad('', cw[0])}{_pad('', cw[1])}{_trunc(orig_name, cw[2]+cw[3]+cw[4]+cw[5]+cw[6]+len(sep)*5)} → 未找到")
    gt = sum(r.get("subtotal", 0) for r in results if r.get("found"))
    if gt > 0:
        lines.append(f"合计: ¥{round(gt, 2)}")
    return "\n".join(lines)


def batch_price(items_text: str) -> dict:
    """批量查多个商品价格（多行报价单），支持自然语言解析。"""
    try:
        lines = items_text.strip().split("\n")
        items = []
        for line in lines:
            item = _parse_batch_line(line)
            if item:
                items.append(item)
        if not items:
            return err_response("无法解析报价文本", "PARSE_ERROR")
        results = []; gt = 0.0; db = get_db()
        for item in items:
            name = item.get("name", ""); qty = item.get("qty", 1)
            rows_list = _rows(db.execute(f"SELECT {_SEARCH_COLS} FROM products WHERE name LIKE ? LIMIT 3", (f"%{name}%",)).fetchall())
            if not rows_list:
                rows_list = _rows(db.execute(f"SELECT {_SEARCH_COLS} FROM products WHERE spec LIKE ? LIMIT 3", (f"%{name}%",)).fetchall())
            if not rows_list:
                rows_list = _rows(db.execute(f"SELECT {_SEARCH_COLS} FROM products WHERE barcode LIKE ? LIMIT 3", (f"%{name}%",)).fetchall())
            candidates = []
            row = rows_list[0] if rows_list else None
            if row:
                st = round(row["sell_price"] * qty, 2); gt += st
                results.append({"name": row["name"], "spec": row.get("spec", ""), "unit_price": row["sell_price"], "qty": qty, "subtotal": st, "found": True, "unit": row.get("unit", "个"), "sku": row.get("sku", ""), "barcode": row.get("barcode", ""), "cost_price": row.get("cost_price", 0), "stock_qty": row.get("stock_qty", 0)})
            else:
                candidates = _find_candidates(name, 3)
                if candidates:
                    best = candidates[0]
                    st = round(best.get("sell_price", 0) * qty, 2)
                    if best.get("sell_price", 0) > 0:
                        gt += st
                    results.append({"name": best["name"], "spec": best.get("spec", ""), "unit_price": best.get("sell_price", 0), "qty": qty, "subtotal": st, "found": True, "found_note": "近似", "unit": best.get("unit", "个"), "sku": best.get("sku", ""), "barcode": best.get("barcode", ""), "cost_price": best.get("cost_price", 0), "stock_qty": best.get("stock_qty", 0)})
                else:
                    results.append({"name": name, "qty": qty, "found": False, "error": "未找到该产品", "candidates": []})
        formatted_reply = _format_batch_reply(results, items)
        quote_text = format_quote(results)
        return {"success": True, "data": {"items": results, "grand_total": round(gt, 2), "item_count": len(results), "quote_text": quote_text}, "error": None, "formatted_reply": formatted_reply}
    except Exception as e:
        return err_response(str(e))


def format_quote(items_data: list) -> str:
    """生成格式化报价单文本。"""
    try:
        lines = []; total = 0.0; i = 1
        qt = "=" * 40 + "\n     示例零售 - 报价单\n" + "=" * 40 + "\n\n"
        for item in items_data:
            nm = item.get("name", ""); sp = item.get("spec", ""); qty = item.get("qty", 1)
            pr = item.get("unit_price", 0)
            unit = item.get("unit", "个")
            st = round(pr * qty, 2); total += st
            ln = f"{i:2d}. {nm} {sp}  x{qty}{unit}  ¥{pr:.2f}  = ¥{st:.2f}"
            qt += ln + "\n"; lines.append(ln); i += 1
        qt += "\n" + "-" * 40 + f"\n    合计: ¥{total:.2f}\n" + "=" * 40 + "\n"
        return qt
    except Exception:
        return "报价单生成失败"


def never_say_no(keyword: str, limit: int = 5) -> dict:
    """零命中兜底链（5 层）— 主检索无结果时的最后挣扎。

    L1 精确名/条码 → L2 LIKE 模糊 → L3 FTS5 语义 → L4 俗语扩展 → L5 分类热门推荐。
    全部无命中时如实返回未找到，不喷全店热门、不虚构调货话术：
    - 反误导口径与 S16c 一致（2026-09-11 老板报障后拍板：未知码/零命中不喷无关商品）；
    - 零命中关键词经 _log_zero_search 进 usage_stats 学习队列（后台「问了没货 TOP15」）。
    历史：本函数曾有不可达的 L6 热门推荐/L7 可调货死代码（L1-5 命中即 return，
    守卫到达时恒真）——I30/A4 于 2026-09-15 移除。若业务要恢复「可调货留联系方式」
    话术，需另立卡并同步 search_products 调用点的 products 非空门与 APP 展示层。
    """
    try:
        db = get_db()
        raw_kw = _normalize_keyword(keyword)
        kw, correction_hint = _correct_search_query(raw_kw)
        deadline = time.time() + SEARCH_TIMEOUT_SECONDS

        # Layer 1: Exact match (name or barcode)
        exact = _rows(db.execute(
            f"SELECT {_SEARCH_COLS} FROM products WHERE name=? COLLATE NOCASE LIMIT ?",
            (kw, limit)
        ).fetchall())
        if not exact:
            exact = _rows(db.execute(
                f"SELECT {_SEARCH_COLS} FROM products WHERE barcode=? COLLATE NOCASE LIMIT ?",
                (kw, limit)
            ).fetchall())

        if exact:
            product = exact[0]
            cross_sell = _get_cross_sell_for(product)
            result = {
                "layer": 1,
                "level": "店有现货 ✅",
                "message": "店里就有，不用愁！",
                "products": exact,
                "cross_sell": cross_sell,
                "location_tip": f"在{_format_location(product.get('location',''))}",
                "correction_hint": correction_hint,
            }
            return _ok(result)

        # Layer 2: LIKE fuzzy search
        similar = _rows(db.execute(
            f"SELECT {_SEARCH_COLS} FROM products WHERE name LIKE ? LIMIT ?",
            (f"%{kw}%", limit)
        ).fetchall())
        if not similar:
            similar = _rows(db.execute(
                f"SELECT {_SEARCH_COLS} FROM products WHERE description LIKE ? LIMIT ?",
                (f"%{kw}%", limit)
            ).fetchall())

        if similar:
            result = {
                "layer": 2,
                "level": "推荐替代品 🔄",
                "message": "这款暂时没货，但给您推荐类似的：",
                "products": similar,
                "reason": _explain_alternative(kw, similar[0]),
                "note": "规格功能相近，完全可以用",
                "correction_hint": correction_hint,
            }
            return _ok(result)

        # Layer 3: FTS5 search
        if time.time() < deadline:
            try:
                pcols = ",".join(f"p.{c}" for c in _SEARCH_COLS.split(","))
                fts_r = _rows(db.execute(
                    f"SELECT {pcols} FROM products p JOIN products_fts f ON p.id=f.rowid WHERE products_fts MATCH ? ORDER BY rank LIMIT ?",
                    (_fts5_safe_query(kw), limit)
                ).fetchall())
            except Exception:
                fts_r = []
            if fts_r:
                result = {
                    "layer": 3,
                    "level": "语义匹配",
                    "message": "没找到完全匹配的，但语义相近的有这些：",
                    "products": fts_r,
                    "reason": "基于FTS5语义推荐",
                    "note": "功能相近，可以满足您的需求",
                    "correction_hint": correction_hint,
                }
                return _ok(result)

        # Layer 4: Colloquial expansion
        if time.time() < deadline:
            colloq = [t for t in _expand_colloquial(kw) if t != kw]
            if colloq:
                seen, syn_results = set(), []
                for term in colloq[:10]:
                    _rs = _search_single(term, limit)
                    if isinstance(_rs, dict):
                        _rs = _rs.get("candidates", [])  # S3 multi 候选照常合并
                    for r in _rs:
                        if r["id"] not in seen:
                            seen.add(r["id"])
                            r["_source"] = f"colloquial:{term}"
                            syn_results.append(r)
                    if len(syn_results) >= limit:
                        break
                if syn_results:
                    result = {
                        "layer": 4,
                        "level": "同义词匹配",
                        "message": f"「{kw}」没找到，但同类型产品有：",
                        "products": syn_results[:limit],
                        "reason": f"根据俗语「{'、'.join(colloq[:5])}」匹配",
                        "note": "这些是同类产品，功能相近",
                        "correction_hint": correction_hint,
                    }
                    return _ok(result)

        # Layer 5: Category recommendation
        category = _infer_category(kw)
        if category:
            cat_products = _get_hot_products_by_category(category, limit)
            if cat_products:
                result = {
                    "layer": 5,
                    "level": "分类推荐 📂",
                    "message": f"「{kw}」没找到，但{category}热门产品有：",
                    "products": cat_products,
                    "reason": f"根据「{kw}」推断属于{category}",
                    "note": f"以下是{category}中热销的商品",
                    "correction_hint": correction_hint,
                }
                return _ok(result)

        # 五层全空 → 如实未找到（不喷全店热门，零命中词已进学习队列）
        return _err_not_found("没找到")
    except Exception as e:
        return _err(str(e))


