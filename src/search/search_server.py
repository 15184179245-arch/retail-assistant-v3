_STOCK_WORDS = "个|只|件|根|米|卷|盒|包|支|套|把|条|桶|片"


def extract_stock_conditions(query: str):
    """S12 阶段2: 从自然语言抽取库存条件（规则优先，零成本确定性）。

    返回 (conditions, cleaned_query)：conditions 只含命中键
    （min_qty/max_qty/location_prefix），无任何库存语义则 ({}, query)。
    店员口头语示例：
      "螺丝 库存大于5"      → {"min_qty": 6}
      "自攻丝 10个以上"     → {"min_qty": 10}
      "A区还剩什么货"       → {"location_prefix": "A"}
      "生料带 没货的"        → {"max_qty": 0}
    """
    import re as _re
    conds = {}
    q = query
    m = _re.search(r"库存[^0-9]{0,3}(\d+)", q)
    if m:
        conds["min_qty"] = int(m.group(1))
        q = q.replace(m.group(0), " ")
    m = _re.search(r"(\d+)\s*(?:" + _STOCK_WORDS + r")?\s*(?:个)?以上", q)
    if m and "min_qty" not in conds:
        conds["min_qty"] = int(m.group(1))
        q = q.replace(m.group(0), " ")
    m = _re.search(r"([A-Za-z])\s*区", q)
    if m:
        conds["location_prefix"] = m.group(1).upper()
        q = _re.sub(r"[A-Za-z]\s*区", " ", q, count=1)
    if _re.search(r"没货|无货|缺货", q):
        conds["max_qty"] = 0
        q = _re.sub(r"没货|无货|缺货", " ", q)
    elif _re.search(r"有货|还有货|在售", q) and "min_qty" not in conds:
        conds["min_qty"] = 1
        q = _re.sub(r"有货|还有货|在售", " ", q, count=1)
    return conds, _re.sub(r"\s{2,}", " ", q).strip()


def apply_stock_filters(rows: list, min_qty=None, max_qty=None, location_prefix=None) -> list:
    """S12 阶段1: 库存维度结构化过滤（纯函数）。

    min_qty: 库存下限（None=不过滤）；location_prefix: 货位前缀（如 "A-1"）。
    行字典缺 stock_qty/location 视为不匹配该条件。
    """
    out = rows
    if min_qty is not None:
        out = [r for r in out if (r.get("stock_qty") or 0) >= min_qty]
    if max_qty is not None:
        out = [r for r in out if (r.get("stock_qty") or 0) <= max_qty]
    if location_prefix:
        pre = location_prefix.strip()
        if pre:
            out = [r for r in out if (r.get("location") or "").startswith(pre)]
    return out


