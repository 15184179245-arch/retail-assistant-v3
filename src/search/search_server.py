class SearchHandler(BaseHTTPRequestHandler):
    """HTTP handler wrapping search functions."""
    def log_message(self, format, *args):
        pass  # suppress default logging

    def _send_json(self, data: dict, status: int = 200, request_id: str = ""):
        if request_id and isinstance(data, dict):
            data["_request_id"] = request_id
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(json.dumps(data, ensure_ascii=False).encode("utf-8"))

    def do_GET(self):
        self.request_id = self.headers.get("X-Request-Id", "")
        set_request_id(self.request_id)
        parsed = urlparse(self.path)
        qs = parse_qs(parsed.query)
        path = parsed.path.rstrip("/")

        if path == "/health":
            result = health_check()
            return self._send_json({"ok": True, "data": result}, request_id=self.request_id)

        if path == "/search":
            keyword = qs.get("keyword", qs.get("q", [""]))[0]
            if not keyword:
                return self._send_json(err_response("缺少 keyword 参数", "MISSING_FIELD"), 400, request_id=self.request_id)
            include_frozen = qs.get("include_frozen", ["0"])[0] in ("1", "true", "yes")
            # S12 阶段1: 库存维度结构化过滤参数
            _mq = qs.get("min_qty", [None])[0]
            min_qty = int(_mq) if _mq not in (None, "") else None
            _xq = qs.get("max_qty", [None])[0]
            max_qty = int(_xq) if _xq not in (None, "") else None
            location_prefix = qs.get("location_prefix", [None])[0] or None
            result = search_products(keyword, include_frozen=include_frozen, min_qty=min_qty, max_qty=max_qty, location_prefix=location_prefix)
            return self._send_json(_attach_sale_freq(result), request_id=self.request_id)

        # B4: 别名解析（只读）——待入库判定与历史账单联查
        if path == "/alias/resolve":
            barcode = (qs.get("barcode", [""])[0] or "").strip()
            if not barcode:
                return self._send_json(err_response("缺少 barcode 参数", "MISSING_FIELD"), 400, request_id=self.request_id)
            result = alias_resolve(barcode)
            return self._send_json(result, request_id=self.request_id)

        # S11: 无售价商品清单（网关 /api/products/unpriced → 本端点）
        if path == "/unpriced":
            kw = (qs.get("kw", [""])[0] or "").strip()
            sale_status = (qs.get("sale_status", [""])[0] or "").strip()
            try:
                page = int(qs.get("page", ["1"])[0])
                page_size = int(qs.get("page_size", [str(UNPRICED_DEFAULT_PAGE_SIZE)])[0])
            except ValueError:
                return self._send_json(
                    err_response("page/page_size 必须是整数", "BAD_REQUEST", "分页参数填写有误"),
                    400, request_id=self.request_id)
            try:
                data = query_unpriced(get_db(), kw=kw, page=page, page_size=page_size,
                                      sale_status=sale_status)
            except Exception as e:
                return self._send_json(
                    err_response(str(e), "DB_ERROR", "读取商品失败，请稍后再试"),
                    500, request_id=self.request_id)
            return self._send_json(ok_response(data), request_id=self.request_id)

        # 智能推荐：五金施工连带辅料与同类在售替代品
        if path == "/recommendations":
            pid = qs.get("product_id", [None])[0]
            name = (qs.get("name", [""])[0] or "").strip()
            cat = (qs.get("category", [""])[0] or "").strip()
            spec = (qs.get("spec", [""])[0] or "").strip()
            _lim = qs.get("limit", ["6"])[0]
            limit = int(_lim) if _lim.isdigit() else 6
            result = get_product_recommendations(product_id=pid, name=name, category=cat, spec=spec, limit=limit)
            return self._send_json(result, request_id=self.request_id)

        self._send_json(err_response(f"未知路径: {path}", "NOT_FOUND"), 404, request_id=self.request_id)

    def do_POST(self):
        self.request_id = self.headers.get("X-Request-Id", "")
        set_request_id(self.request_id)
        content_length = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_length) if content_length else b"{}"
        parsed = urlparse(self.path)
        path = parsed.path.rstrip("/")

        if path == "/search":
            data, err = validate_request(body, {
                "keyword": {"required": True, "message": "请输入搜索关键词"},
            })
